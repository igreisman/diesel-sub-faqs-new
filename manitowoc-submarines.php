            <h2 class="h5 mb-3">Why did we build submarines in Manitowoc, Wisconsin? How did they get from Lake Michigan to the oceans?</h2>

            <p class="lead">The simplest answer is that we could build more boats with the additional shipyard. Manitowoc Shipbuilding was a quality company that was looking for military contracts to keep their employees working during WW2. At the same time, the Navy was looking for another commercial shipyard to build submarines. However, the full story is more complex and more interesting.</p>

            <p>The head of the Manitowoc shipyard, Charles West, had worked as Supervisor of Naval Construction previously, during World War 1. This was at the Ford Motor Company shipbuilding plant at River Rouge. He had supervised the building of small escorts for 18 months. As WW2 began in Europe, Mr. West contacted the Navy and offered to have Manitowoc Shipbuilding build small escort ships. They asked him to build submarines instead. He turned the Navy down because he had never built a submarine which is complex, oddly shaped and has many tight spaces.</p>

            <p>When another shipbuilding appropriation was passed in 1940, the Navy came back to Mr. West and again asked him to build submarines. This time, the Navy offered the assistance of the Electric Boat Company, our primary civilian shipyard for submarines at the time. Agreements were signed. Manitowoc Shipbuilding completed 28 submarines during WW2. The crews generally thought these were higher quality boats. However, there were challenges to be overcome:</p>

            <ul>
                <li class="mb-2">These boats would be built in a fresh water port, which meant that the boats would, in effect, appear to be much heavier since fresh water was less dense than sea water. Fresh water doesn&rsquo;t support as much weight. Initial trim dives had to be ballasted differently, with far less weight in the boat.</li>
                <li class="mb-2">Launching was sideways. The shipyard had to calculate the roll of the boat and ensure that it wasn&rsquo;t damaged in the launching.</li>
                <li class="mb-2">Winters were colder than in the shipyards on the coast. Fresh water also freezes sooner, at a higher temperature. Ice accumulation on the superstructure of any ship can be very dangerous.</li>
                <li class="mb-2">The biggest challenge was getting the submarines to the ocean. The St. Lawrence and Erie Canals were too small for submarines and the St. Lawrence Seaway wasn&rsquo;t completed until 1959. The answer was to tow the submarines through Chicago to Lockport, IL. There the boat would be put on a floating drydock and that would be towed to New Orleans. There were many lesser issues with towing the boats, such as getting under some bridges in spring and tying up to trees on the river banks when waiting for water levels to rise or fall.</li>
            </ul>

            <p>However, Manitowoc Shipbuilding solved them all. Nearly all of the 28 boats were completed ahead of schedule and under budget. In fact, the 28th boat, the last of the second contract, was delivered before the 10th one, the last in the first contract, was due.</p>
