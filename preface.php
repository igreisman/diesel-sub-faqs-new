            <h1 class="mb-4">Preface</h1>

            <p class="lead">Each Memorial Day, United States Submarine Veterans read the list of the boats lost in World War 2. It is called the &ldquo;Tolling of the Boats.&rdquo; The reading of the names of the lost boats typically includes the number of sailors lost with each one. Since the ceremony was created by WW2 sub vets, the focus was on their era. Recently the list has included the four submarines that we have lost since the war. Although they were not lost in active combat, we acknowledge that these sailors also gave their lives in the service of their country.</p>

            <p>This reading has not usually included the submarines we lost prior to WW2. We had an average of one submarine incident (sinking or grounding) every 27 months from the time of the USS <em>Holland</em> purchase in 1900 until the outbreak of WW2 in 1941. However, a number of those boats sank without loss of life and were salvaged and recommissioned. Therefore, we made an arbitrary decision about which boats to include in our list of those lost prior to WW2. We only included the eleven U.S. Navy submarines lost prior to WW2 with loss of life or where the boat was not salvaged.</p>

            <p><a href="other-boats.php">For more information on the boats we did not include, click here.</a></p>

            <h2 class="h5 mt-4 mb-2">So how did this particular project come about?</h2>

            <p>This project came about for the Maritime Museum in San Francisco, custodian of the USS <em>Pampanito</em> (SS-383). The Mare Island base of the USSVI sub vets normally holds their &ldquo;Tolling of the Boats&rdquo; at the <em>Pampanito</em>. This document is an effort to make the list more inclusive and to give it more texture, more depth and, hopefully, make it more interesting. Although this document is too lengthy to be read in full at the ceremony, we hope it might provide more information for anyone who might be interested.</p>

            <p>Some of the stories of the lost submarines are interesting or particularly tragic. Most of them had interesting histories prior to their last patrols. That is the sort of thing we wanted to convey. For example, one boat rescued gold bars and silver coins from banks in the Philippines, only to have one gold bar go &ldquo;missing&rdquo; on the way home. One submarine sank a Japanese carrier but wasn&rsquo;t immediately aware of it. The submarine was long gone before the carrier went down. The stories of the sister ships USS <em>Squalus/Sailfish</em> and the USS <em>Sculpin</em> are particularly ironic and sad. There was also the frequent tension between what captains thought they sank and what they got credit for in the postwar audit.</p>

            <h2 class="h5 mt-4 mb-2">How is the document organized?</h2>

            <p>The prewar losses that met our criteria are listed in section 1. Section 2 details the WW2 losses and postwar losses are in section 3. The listings are generally in order of the dates the boats were lost. That isn&rsquo;t an exact sort since we still don&rsquo;t always know the specific dates of each of the losses.</p>

            <p>For each listing, we start with basic information about the boat such as the class and building shipyard. Next, we describe the last patrol and what we know about the submarine&rsquo;s loss. Then we go back and summarize its prior history.</p>

            <p>The officers&rsquo; photographs, unless otherwise noted, are those of the last commanding officers. Although the majority of the captains, and their crews, were lost when the boat went down, not all perished. In two cases, the captains are listed with two different boats. In four cases the boats went aground and the entire crews were rescued. In a few more cases, captains were on the bridge when the boat was sunk and they, along with a few other crew members were able to make it to safety.</p>

            <p>The pictures of the submarines, again unless otherwise noted, are those of the lost boats. Obviously, there may not be much difference between boats of the same classes, but there are huge differences between our first class of submarines, such as the <em>A-7</em>, and the nuclear-powered boats. Manitowoc boats were launched sideways and that process looks very different. Therefore, we included the photos of many of the boats.</p>

